// location says whether assets are written for the current project or for the
// user.
type location string

const (
	locLocal  location = "local"
	locGlobal location = "global"
)

const generatedHeader = "<!-- generated by agenthub; do not edit -->"

// env carries the directories a materialization is relative to.
type env struct {
	Home string // user home directory, base of the global location
	Cwd  string // project directory, base of the local location
}

// base is the directory state and relative paths of loc hang off.
func (e env) base(loc location) string {
	if loc == locGlobal {
		return e.Home
	}
	return e.Cwd
}

// stateFile is the drift record of one location.
func (e env) stateFile(loc location) string {
	if loc == locGlobal {
		return filepath.Join(e.Home, ".agenthub", "state.json")
	}
	return filepath.Join(e.Cwd, ".agenthub", "state.json")
}

// manifestDoc is the subset of a bundle manifest the harness writers read
// (docs/architecture/domain-model.md §2–§3).
type manifestDoc struct {
	Kind        string `json:"kind"`
	Namespace   string `json:"namespace"`
	Name        string `json:"name"`
	Version     string `json:"version"`
	DisplayName string `json:"displayName"`
	Summary     string `json:"summary"`
	Files       []struct {
		Path   string `json:"path"`
		Sha256 string `json:"sha256"`
	} `json:"files"`
	Spec struct {
		Agent struct {
			Prompt string `json:"prompt"`
			Mode   string `json:"mode"`
		} `json:"agent"`
		Skill struct {
			Entry string `json:"entry"`
		} `json:"skill"`
		Prompt struct {
			Target   string `json:"target"`
			Template string `json:"template"`
		} `json:"prompt"`
	} `json:"spec"`
}

// materialAsset is a locked asset with its manifest and cached files loaded.
type materialAsset struct {
	Ref     string
	Doc     manifestDoc
	Files   map[string][]byte // bundle path -> bytes
	Missing []string          // declared files that are not in the cache
}

// cleanBundlePath normalizes a bundle-relative path and rejects anything that
// could escape the bundle.
func cleanBundlePath(p string) (string, error) {
	c := path.Clean(strings.TrimPrefix(strings.ReplaceAll(p, "\\", "/"), "./"))
	if c == "." || path.IsAbs(c) || c == ".." || strings.HasPrefix(c, "../") {
		return "", fmt.Errorf("unsafe bundle path %q", p)
	}
	return c, nil
}

// loadAsset reads an installed asset out of the cache.
func loadAsset(c *cache.Cache, pin lockfile.LockedAsset) (*materialAsset, error) {
	if strings.TrimSpace(pin.ManifestDigest) == "" {
		return nil, fmt.Errorf("%s: no manifest digest in lockfile", pin.Ref)
	}
	key, err := cache.KeyFromDigest(pin.ManifestDigest)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", pin.Ref, err)
	}
	raw, err := c.Get(key)
	if err != nil {
		return nil, fmt.Errorf("%s: manifest not installed: %w", pin.Ref, err)
	}
	a := &materialAsset{Ref: pin.Ref, Files: map[string][]byte{}}
	if err := json.Unmarshal(raw, &a.Doc); err != nil {
		return nil, fmt.Errorf("%s: parse manifest: %w", pin.Ref, err)
	}
	for _, f := range a.Doc.Files {
		p, err := cleanBundlePath(f.Path)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", pin.Ref, err)
		}
		fk, err := cache.KeyFromDigest(f.Sha256)
		if err != nil {
			a.Missing = append(a.Missing, p)
			continue
		}
		body, err := c.Get(fk)
		if err != nil {
			a.Missing = append(a.Missing, p)
			continue
		}
		a.Files[p] = body
	}
	return a, nil
}

// file returns the bytes of a bundle path named by the spec.
func (a *materialAsset) file(p string) ([]byte, bool) {
	if p == "" {
		return nil, false
	}
	c, err := cleanBundlePath(p)
	if err != nil {
		return nil, false
	}
	b, ok := a.Files[c]
	return b, ok
}

func (a *materialAsset) stem() string { return a.Doc.Namespace + "-" + a.Doc.Name }

func (a *materialAsset) description() string {
	if a.Doc.Summary != "" {
		return a.Doc.Summary
	}
	if a.Doc.DisplayName != "" {
		return a.Doc.DisplayName
	}
	return a.Doc.Name
}

func (a *materialAsset) title() string {
	if a.Doc.DisplayName != "" {
		return a.Doc.DisplayName
	}
	return a.Doc.Name
}

// body is the Markdown payload of the asset: the agent prompt, the skill entry
// or the prompt template. Frontmatter the bundle already carries is dropped so
// each harness can write its own.
func (a *materialAsset) body() ([]byte, error) {
	var p string
	switch a.Doc.Kind {
	case "agent":
		p = a.Doc.Spec.Agent.Prompt
	case "skill":
		p = a.Doc.Spec.Skill.Entry
		if p == "" {
			p = "SKILL.md"
		}
	case "prompt":
		p = a.Doc.Spec.Prompt.Template
	}
	b, ok := a.file(p)
	if !ok {
		return nil, fmt.Errorf("%s: %s file %q is not installed", a.Ref, a.Doc.Kind, p)
	}
	return stripFrontmatter(b), nil
}

// stripFrontmatter removes a leading YAML frontmatter block.
func stripFrontmatter(b []byte) []byte {
	if !bytes.HasPrefix(b, []byte("---\n")) {
		return b
	}
	rest := b[4:]
	if i := bytes.Index(rest, []byte("\n---\n")); i >= 0 {
		return bytes.TrimLeft(rest[i+5:], "\n")
	}
	return b
}

// frontmatter renders key/value pairs as a YAML block; empty values are
// skipped and strings are JSON-quoted, which is valid YAML.
func frontmatter(kv ...string) string {
	var sb strings.Builder
	sb.WriteString("---\n")
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] == "" {
			continue
		}
		if kv[i+1] == "false" || kv[i+1] == "true" {
			fmt.Fprintf(&sb, "%s: %s\n", kv[i], kv[i+1])
			continue
		}
		q, _ := json.Marshal(kv[i+1])
		fmt.Fprintf(&sb, "%s: %s\n", kv[i], q)
	}
	sb.WriteString("---\n")
	return sb.String()
}

// planFile is one file a harness writer wants on disk.
type planFile struct {
	Path    string // absolute
	Content []byte
}

// planSection is a block inside a shared file (AGENTS.md).
type planSection struct {
	Path string // absolute
	ID   string
	Body string
}

// plan is everything one harness writes for a set of assets.
type plan struct {
	Files    []planFile
	Sections []planSection
	Notes    []string
}

// harness is one agent tool assets can be installed into.
type harness struct {
	ID     string
	Name   string
	Global bool // supports the global location
	// Detect reports whether the tool looks installed on this machine.
	Detect func(home string) bool
	// Root is the directory the harness reads its assets from.
	Root func(loc location, e env) string
	// Asset plans the files of one asset under root.
	Asset func(root string, loc location, a *materialAsset) (plan, error)
}

func onPath(name string) bool {
	_, err := exec.LookPath(name)
	return err == nil
}

func dirExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && st.IsDir()
}

// markdownFile renders a frontmatter-plus-body file with the generated header.
func markdownFile(fm string, body []byte) []byte {
	return []byte(fm + "\n" + generatedHeader + "\n\n" + strings.TrimLeft(string(body), "\n"))
}

// skillFiles copies the whole skill directory.
func skillFiles(root string, a *materialAsset) plan {
	var p plan
	names := make([]string, 0, len(a.Files))
	for n := range a.Files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p.Files = append(p.Files, planFile{Path: filepath.Join(root, "skills", a.Doc.Name, filepath.FromSlash(n)), Content: a.Files[n]})
	}
	for _, m := range a.Missing {
		p.Notes = append(p.Notes, fmt.Sprintf("%s: file %s not in cache", a.Ref, m))
	}
	return p
}

// dirHarness builds a harness whose assets are files in agents/, skills/ and a
// command directory under one root.
func dirHarness(id, name string, global bool, detect func(string) bool, root func(location, env) string,
	agentFile func(a *materialAsset) string, commandDir, commandExt string,
) harness {
	return harness{
		ID: id, Name: name, Global: global, Detect: detect, Root: root,
		Asset: func(r string, loc location, a *materialAsset) (plan, error) {
			switch a.Doc.Kind {
			case "agent":
				body, err := a.body()
				if err != nil {
					return plan{}, err
				}
				fm := frontmatter("name", a.stem(), "description", a.description())
				if id == "opencode" {
					mode := a.Doc.Spec.Agent.Mode
					if mode == "" {
						mode = "subagent"
					}
					fm = frontmatter("description", a.description(), "mode", mode)
				}
				return plan{Files: []planFile{{Path: filepath.Join(r, agentFile(a)), Content: markdownFile(fm, body)}}}, nil
			case "skill":
				if _, err := a.body(); err != nil {
					return plan{}, err
				}
				return skillFiles(r, a), nil
			case "prompt":
				if commandDir == "" || (loc == locGlobal && id == "copilot") {
					return plan{Notes: []string{fmt.Sprintf("%s: prompts are not supported by %s here", a.Ref, name)}}, nil
				}
				body, err := a.body()
				if err != nil {
					return plan{}, err
				}
				fm := frontmatter("description", a.description())
				return plan{Files: []planFile{{Path: filepath.Join(r, commandDir, a.Doc.Name+commandExt), Content: markdownFile(fm, body)}}}, nil
			default:
				return plan{Notes: []string{fmt.Sprintf("%s: %s assets are not materialized", a.Ref, a.Doc.Kind)}}, nil
			}
		},
	}
}

// harnesses returns the supported targets in display order.
func harnesses() []harness {
	stemMD := func(a *materialAsset) string { return filepath.Join("agents", a.stem()+".md") }
	return []harness{
		dirHarness("claude", "Claude Code", true,
			func(h string) bool { return dirExists(filepath.Join(h, ".claude")) || onPath("claude") },
			func(loc location, e env) string { return filepath.Join(e.base(loc), ".claude") },
			stemMD, "commands", ".md"),
		dirHarness("opencode", "opencode", true,
			func(h string) bool { return dirExists(filepath.Join(h, ".config", "opencode")) || onPath("opencode") },
			func(loc location, e env) string {
				if loc == locGlobal {
					return filepath.Join(e.Home, ".config", "opencode")
				}
				return filepath.Join(e.Cwd, ".opencode")
			},
			stemMD, "commands", ".md"),
		dirHarness("copilot", "GitHub Copilot", true,
			func(h string) bool { return dirExists(filepath.Join(h, ".copilot")) || onPath("copilot") },
			func(loc location, e env) string {
				if loc == locGlobal {
					return filepath.Join(e.Home, ".copilot")
				}
				return filepath.Join(e.Cwd, ".github")
			},
			func(a *materialAsset) string { return filepath.Join("agents", a.stem()+".agent.md") }, "prompts", ".prompt.md"),
		cursorHarness(),
		codexHarness(),
	}
}

func cursorHarness() harness {
	return harness{
		ID: "cursor", Name: "Cursor", Global: false,
		Detect: func(h string) bool { return dirExists(filepath.Join(h, ".cursor")) },
		Root:   func(loc location, e env) string { return filepath.Join(e.base(loc), ".cursor") },
		Asset: func(root string, _ location, a *materialAsset) (plan, error) {
			if a.Doc.Kind != "agent" && a.Doc.Kind != "skill" && a.Doc.Kind != "prompt" {
				return plan{Notes: []string{fmt.Sprintf("%s: %s assets are not materialized", a.Ref, a.Doc.Kind)}}, nil
			}
			body, err := a.body()
			if err != nil {
				return plan{}, err
			}
			fm := frontmatter("description", a.description(), "alwaysApply", "false")
			return plan{Files: []planFile{{Path: filepath.Join(root, "rules", a.stem()+".mdc"), Content: markdownFile(fm, body)}}}, nil
		},
	}
}

func codexHarness() harness {
	return harness{
		ID: "codex", Name: "Codex CLI", Global: true,
		Detect: func(h string) bool { return dirExists(filepath.Join(h, ".codex")) || onPath("codex") },
		Root: func(loc location, e env) string {
			if loc == locGlobal {
				return filepath.Join(e.Home, ".codex")
			}
			return e.Cwd
		},
		Asset: func(root string, _ location, a *materialAsset) (plan, error) {
			if a.Doc.Kind != "agent" && a.Doc.Kind != "skill" && a.Doc.Kind != "prompt" {
				return plan{Notes: []string{fmt.Sprintf("%s: %s assets are not materialized", a.Ref, a.Doc.Kind)}}, nil
			}
			body, err := a.body()
			if err != nil {
				return plan{}, err
			}
			text := fmt.Sprintf("## %s (%s)\n\n%s\n\n%s", a.title(), a.Doc.Kind, a.description(), strings.TrimSpace(string(body)))
			id := a.Doc.Namespace + "/" + a.Doc.Kind + "/" + a.Doc.Name
			return plan{Sections: []planSection{{Path: filepath.Join(root, "AGENTS.md"), ID: id, Body: text}}}, nil
		},
	}
}

func findHarness(id string) (harness, bool) {
	for _, h := range harnesses() {
		if h.ID == id {
			return h, true
		}
	}
	return harness{}, false
}

