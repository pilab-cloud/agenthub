// installState records what agenthub wrote so later runs can tell its files
// from the user's edits.
type installState struct {
	Harnesses []string             `json:"harnesses"`
	Files     map[string]stateFile `json:"files"`
}

type stateFile struct {
	Sha256  string `json:"sha256"`
	Harness string `json:"harness"`
}

func loadState(p string) (installState, error) {
	st := installState{Files: map[string]stateFile{}}
	raw, err := os.ReadFile(p) //nolint:gosec // path is derived from the project or home directory
	if errors.Is(err, os.ErrNotExist) {
		return st, nil
	}
	if err != nil {
		return st, err
	}
	if err := json.Unmarshal(raw, &st); err != nil {
		return st, fmt.Errorf("read %s: %w", p, err)
	}
	if st.Files == nil {
		st.Files = map[string]stateFile{}
	}
	return st, nil
}

func saveState(p string, st installState) error {
	sort.Strings(st.Harnesses)
	raw, err := json.MarshalIndent(st, "", "  ")
	if err != nil {
		return err
	}
	return writeFileAtomic(p, append(raw, '\n'))
}

func writeFileAtomic(p string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".agenthub-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		_ = os.Remove(name)
		return err
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(name)
		return err
	}
	if err := os.Chmod(name, 0o644); err != nil { //nolint:gosec // generated assets are meant to be readable
		_ = os.Remove(name)
		return err
	}
	return os.Rename(name, p)
}

func sum(b []byte) string {
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:])
}

// applyResult counts what a materialization did.
type applyResult struct {
	Written, Unchanged, Removed, Drift int
	Notes                              []string
}

func (r *applyResult) add(o applyResult) {
	r.Written += o.Written
	r.Unchanged += o.Unchanged
	r.Removed += o.Removed
	r.Drift += o.Drift
	r.Notes = append(r.Notes, o.Notes...)
}

// buildPlan merges the plans of every asset for one harness; assets that
// cannot be planned become notes instead of failing the run.
func buildPlan(h harness, loc location, e env, assets []*materialAsset) plan {
	root := h.Root(loc, e)
	var total plan
	for _, a := range assets {
		p, err := h.Asset(root, loc, a)
		if err != nil {
			total.Notes = append(total.Notes, err.Error())
			continue
		}
		total.Files = append(total.Files, p.Files...)
		total.Sections = append(total.Sections, p.Sections...)
		total.Notes = append(total.Notes, p.Notes...)
	}
	return total
}

// applyPlan writes p for harness h into loc, tracking drift in st.
func applyPlan(h harness, loc location, e env, p plan, st *installState, force bool) (applyResult, error) {
	res := applyResult{Notes: p.Notes}
	base := e.base(loc)
	rel := func(abs string) string {
		if r, err := filepath.Rel(base, abs); err == nil {
			return filepath.ToSlash(r)
		}
		return filepath.ToSlash(abs)
	}

	keep := map[string]bool{}
	for _, f := range p.Files {
		key := rel(f.Path)
		keep[key] = true
		existing, err := os.ReadFile(f.Path) //nolint:gosec // path is built from the harness root
		switch {
		case errors.Is(err, os.ErrNotExist):
		case err != nil:
			return res, err
		case bytes.Equal(existing, f.Content):
			st.Files[key] = stateFile{Sha256: sum(f.Content), Harness: h.ID}
			res.Unchanged++
			continue
		default:
			if rec, ok := st.Files[key]; !force && (!ok || rec.Sha256 != sum(existing)) {
				res.Drift++
				res.Notes = append(res.Notes, fmt.Sprintf("drift: %s was modified locally; skipped (use --force)", key))
				continue
			}
		}
		if err := writeFileAtomic(f.Path, f.Content); err != nil {
			return res, err
		}
		st.Files[key] = stateFile{Sha256: sum(f.Content), Harness: h.ID}
		res.Written++
	}

	for _, s := range p.Sections {
		changed, err := upsertSection(s)
		if err != nil {
			return res, err
		}
		if changed {
			res.Written++
		} else {
			res.Unchanged++
		}
	}

	// Files recorded for this harness that no asset produces any more.
	for key, rec := range st.Files {
		if rec.Harness != h.ID || keep[key] {
			continue
		}
		abs := filepath.Join(base, filepath.FromSlash(key))
		existing, err := os.ReadFile(abs) //nolint:gosec // path comes from agenthub's own state file
		if errors.Is(err, os.ErrNotExist) {
			delete(st.Files, key)
			continue
		}
		if err != nil {
			return res, err
		}
		if rec.Sha256 != sum(existing) && !force {
			res.Drift++
			res.Notes = append(res.Notes, fmt.Sprintf("drift: stale %s was modified locally; kept", key))
			continue
		}
		if err := os.Remove(abs); err != nil {
			return res, err
		}
		delete(st.Files, key)
		res.Removed++
	}
	return res, nil
}

func sectionMarkers(id string) (string, string) {
	return "<!-- agenthub:begin " + id + " -->", "<!-- agenthub:end " + id + " -->"
}

// upsertSection inserts or replaces one marked block in a shared file and
// reports whether the file changed.
func upsertSection(s planSection) (bool, error) {
	begin, end := sectionMarkers(s.ID)
	block := begin + "\n" + s.Body + "\n" + end
	raw, err := os.ReadFile(s.Path) //nolint:gosec // path is built from the harness root
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	text := string(raw)
	var next string
	if i := strings.Index(text, begin); i >= 0 {
		j := strings.Index(text[i:], end)
		if j < 0 {
			return false, fmt.Errorf("%s: unterminated agenthub block %s", s.Path, s.ID)
		}
		next = text[:i] + block + text[i+j+len(end):]
	} else {
		next = strings.TrimRight(text, "\n")
		if next != "" {
			next += "\n\n"
		}
		next += block + "\n"
	}
	if next == text {
		return false, nil
	}
	return true, writeFileAtomic(s.Path, []byte(next))
}
